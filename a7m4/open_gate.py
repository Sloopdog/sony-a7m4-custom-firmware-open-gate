def _int(value: str | int) -> int:
    return value if isinstance(value, int) else int(value, 0)


def _config_header(lay: dict, record: dict) -> str:
    """og_config.h: every camera constant og_mem.c, og.c and og_menu.c use, from layout.json and stored_record.json.
    The menu constants have no C suffix: og_menu_entry.S includes the header too."""
    cam, loc, fam = lay["camera"], record["locator"], record["families"]
    va_end = _int(loc["cp_va_range"][1]) + _int(loc["q_field_in_p"]) + 4
    require(va_end == 1 << 28, "OG_LAYOUT", "stored_record.json's CP range no longer ends at 0x10000000")
    rows = [("OG_SYM_DMM_ALLOC", json.dumps(cam["dmm_symbols"]["alloc"])),
            ("OG_SYM_DMM_FREE", json.dumps(cam["dmm_symbols"]["free"])),
            ("OG_SYM_DMA", json.dumps(cam["dmm_symbols"]["dma"])),
            ("OG_DMM_BYTES", f"{_int(cam['dmm_buffer_bytes']):#x}u"),
            ("OG_DMM_PHYS_MIN", f"{_int(cam['dmm_phys_min']):#x}ull"),
            ("OG_DMM_PHYS_END", f"{_int(cam['dmm_phys_end']):#x}ull"),
            ("OG_AVCAM_PHYS", f"{_int(cam['avcam_phys']):#x}ull"),
            ("OG_AVCAM_MAP_OFFSET", f"{_int(cam['avcam_map_offset']):#x}u"),
            ("OG_AVCAM_MAP_BYTES", f"{_int(cam['avcam_map_bytes']):#x}u"),
            ("OG_DIAL_MOVIE", f"{_int(cam['dial_movie'])}u"),
            ("OG_RECORD_ROOT", f"{_int(loc['root_cp_va']):#x}u"),
            ("OG_RECORD_P_FIELD", f"{_int(loc['p_field']):#x}u"),
            ("OG_RECORD_Q_FIELD", f"{_int(loc['q_field_in_p']):#x}u"),
            ("OG_RECORD_COUNT_FIELD", f"{_int(loc['count_field_in_q']):#x}u"),
            ("OG_RECORD_COUNT_MIN", f"{_int(loc['count_range'][0])}u"),
            ("OG_RECORD_COUNT_MAX", f"{_int(loc['count_range'][1])}u"),
            ("OG_RECORD_LIST_FIELD", f"{_int(loc['mode_list_field_in_q']):#x}u"),
            ("OG_RECORD_RECORDS_FIELD", f"{_int(loc['records_field_in_q']):#x}u"),
            ("OG_RECORD_BYTES", f"{_int(loc['record_bytes'])}u"),
            ("OG_CP_VA_MIN", f"{_int(loc['cp_va_range'][0]):#x}u"),
            ("OG_CP_VA_END", f"{va_end:#x}u"),
            ("OG_DRIVE_MODE_NTSC", f"{_int(fam['ntsc']['drive_mode']):#x}u"),
            ("OG_DRIVE_MODE_PAL", f"{_int(fam['pal']['drive_mode']):#x}u")]
    menu = lay["menu"]
    rows += [("OG_MENU_MID", str(_int(menu["mid"]))), ("OG_MENU_ALIAS_BASE", str(_int(menu["alias_base"])))]
    rows += [(f"OG_MENU_TEXT_{k.upper()}", f"{_int(v):#010x}") for k, v in menu["text"].items()]
    return ("/* Generated by a7m4/open_gate.py from native/open-gate/layout.json and stored_record.json. */\n"
            "#ifndef OG_CONFIG_H\n#define OG_CONFIG_H\n" + "".join(f"#define {k} {v}\n" for k, v in rows) + "#endif\n")


def _linker_script(lay: dict) -> str:
    ap = lay["appfw"]
    rx, rw = _int(ap["rx"]["va"]), _int(ap["rw"]["va"])
    names = {"dlsym": lay["stock_functions"]["dlsym"], "native_mode": lay["stock_functions"]["native_mode"]}
    names |= {h["previous_symbol"]: h["previous_target"] for h in lay["hooks"]}
    menu = lay["menu"]
    names |= {f"og_native_register_{k}": v for k, v in menu["registrars"].items()}
    names |= {f"og_native_map_{k}": v["va"] for k, v in menu["maps"].items() if k != "what"}
    names |= {"og_native_true": menu["stock"]["native_true"]["va"], "og_menu_apply_custom": menu["stock"]["apply_custom"]["va"]}
    return ("ENTRY(og_hook_first)\nSECTIONS {\n"
            f" .text {rx:#x} : {{ *(.text*) *(.rodata*) }}\n"
            f" ASSERT(. <= {rx + _int(ap['rx']['max_bytes']):#x}, \"open-gate code and site image exceed the RX section\")\n"
            f" .bss {rw:#x} (NOLOAD) : {{ *(.bss*) *(COMMON) }}\n"
            f" ASSERT(. <= {rw + _int(ap['rw']['max_bytes']):#x}, \"open-gate state exceeds the RW section\")\n"
            " /DISCARD/ : { *(.eh_frame*) *(.comment*) *(.note*) }\n}\n"
            + "".join(f"{k} = {_int(v):#x};\n" for k, v in names.items()))


def _check_sources(lay: dict) -> dict:
    pins = lay["sources"]
    require(set(pins) == set(_SOURCES + _HEADERS), "OG_SOURCE", "layout.json pins a different source set")
    for name, value in pins.items():
        actual = sha256(_NATIVE / name)
        require(actual == value, "OG_SOURCE", f"native/open-gate/{name}: SHA-256 {actual} is not the pinned {value}")
    return dict(pins)


def compile_module(zig: Path, image: SiteImage, workdir: Path) -> Module:
    """Write image.encode() as og_sites.bin and link native/open-gate at layout.json's fixed VAs."""
    from elftools.elf.elffile import ELFFile
    lay = _layout()
    # zig runs with cwd=workdir, so every path it is given must be absolute.
    zig, workdir = Path(zig).resolve(), Path(workdir).resolve()
    actual = sha256(zig)
    require(actual == lay["compiler"]["sha256"], "OG_COMPILER", f"Zig binary SHA-256 {actual} is not the pinned one")
    _check_sources(lay)
    workdir.mkdir(parents=True, exist_ok=False)
    blob = image.encode()
    (workdir / "og_sites.bin").write_bytes(blob)
    (workdir / "og_config.h").write_text(_config_header(lay, json.loads(_STORED_RECORD.read_text("utf-8"))), "utf-8")
    (workdir / "open_gate.ld").write_text(_linker_script(lay), "utf-8")
    elf_path = workdir / "open_gate.elf"
    # The link drops sections nothing reaches from the entry; every hook entry is reached only from appFw.so.
    command = [str(zig), "cc", *_CFLAGS, "-Wl,-e,og_hook_first", *(f"-Wl,-u,{h['entry']}" for h in lay["hooks"]),
               "-Wl,-T," + str(workdir / "open_gate.ld"),
               "-I", str(workdir), "-I", str(_NATIVE), *[str(_NATIVE / s) for s in _SOURCES], "-o", str(elf_path)]
    subprocess.run(command, check=True, cwd=workdir)
    (workdir / "command.json").write_text(json.dumps(command, indent=1) + "\n", "utf-8")
    elf = ELFFile(io.BytesIO(elf_path.read_bytes()))
    ap = lay["appfw"]
    rx, rw = _int(ap["rx"]["va"]), _int(ap["rw"]["va"])
    alloc = [s for s in elf.iter_sections() if s["sh_flags"] & 2 and s["sh_size"]]
    require(sorted(s.name for s in alloc) in (sorted([".text", ".bss"]), [".text"]), "OG_LINK",
            "Unexpected allocated sections: " + ", ".join(s.name for s in alloc))
    text = elf.get_section_by_name(".text")
    bss = elf.get_section_by_name(".bss")
    require(text["sh_addr"] == rx and text["sh_size"] <= _int(ap["rx"]["max_bytes"]), "OG_LINK", "RX placement")
    state = bss["sh_size"] if bss else 0
    require(not bss or (bss["sh_addr"] == rw and state <= _int(ap["rw"]["max_bytes"])), "OG_LINK", "RW placement")
    require(not [s for s in elf.iter_sections() if s["sh_type"] in ("SHT_REL", "SHT_RELA") and s["sh_size"]],
            "OG_LINK", "The module needs relocations")
    symtab = elf.get_section_by_name(".symtab")
    require(not [s.name for s in symtab.iter_symbols() if s.name and s["st_shndx"] == "SHN_UNDEF"], "OG_LINK",
            "Undefined symbols")
    symbols = {s.name: s["st_value"] for s in symtab.iter_symbols()
               if s.name and s["st_info"]["type"] in ("STT_FUNC", "STT_OBJECT", "STT_NOTYPE")
               and s["st_shndx"] not in ("SHN_UNDEF",)}
    code = text.data()
    pin = lay["module"]
    require(len(code) == pin["text_bytes"] and digest(code) == pin["text_sha256"], "OG_LINK",
            f"Linked module {digest(code)} is not the pinned build")
    at = symbols["og_sites"] - rx
    require(code[at:at + len(blob)] == blob, "OG_LINK", "Linked site image differs from og_sites.bin")
    for name in ("og_hook_first", "og_hook_second", "og_power_on", "og_select", "og_selected",
                 *(h["entry"] for h in lay["hooks"]), "og_menu_getter", "og_menu_setter", "og_menu_commit",
                 "og_menu_profile_blocked", "og_menu_default"):
        require(rx <= symbols.get(name, 0) < rx + len(code), "OG_LINK", f"{name} is not in the module")
    records = symbols.get("og_menu_records", 0)
    require(records % 16 == 0 and rw <= records and records + _MENU_RECORD_BYTES <= rw + state, "OG_LINK",
            "og_menu_records is not in the module's RW section")
    return Module(code, rx, rw, state, symbols)


def _branch(pc: int, target: int, link: bool) -> bytes:
    """B (link False) or BL from pc to target."""
    delta = target - pc
    require(delta % 4 == 0 and -(1 << 27) <= delta < 1 << 27, "OG_HOOK", "Branch target out of range")
    return struct.pack("<I", (0x94000000 if link else 0x14000000) | ((delta >> 2) & 0x3ffffff))


def _check_menu_stock(appfw: bytes, elf, loads, layout: dict) -> None:
    """Every stock address og_menu.c uses: each map's GOT slot is an R_AARCH64_RELATIVE to the map's VA, each registrar
    and helper starts with the expected bytes."""
    import numpy as np
    menu = layout["menu"]
    rela = elf.get_section_by_name(".rela.dyn")
    table = np.frombuffer(appfw, dtype="<u8", count=rela["sh_size"] // 8, offset=rela["sh_offset"]).reshape(-1, 3)

    def at(va: int, size: int) -> bytes:
        load = next((s for s in loads if s["p_vaddr"] <= va and va + size <= s["p_vaddr"] + s["p_filesz"]), None)
        require(load is not None, "OG_MENU", f"{va:#x} is not file-backed")
        offset = load["p_offset"] + va - load["p_vaddr"]
        return appfw[offset:offset + size]

    for name, entry in ((k, v) for k, v in menu["maps"].items() if k != "what"):
        rows = table[table[:, 0] == _int(entry["got"])]
        require(len(rows) == 1 and int(rows[0, 1]) == _R_RELATIVE and int(rows[0, 2]) == _int(entry["va"]), "OG_MENU",
                f"GOT slot {entry['got']} is not a RELATIVE to the {name} map {entry['va']}")
    for name, va in menu["registrars"].items():
        require(at(_int(va), 4) == bytes.fromhex(menu["stock"]["registrar"]), "OG_MENU", f"{name} registrar {va}")
    for name in ("native_true", "apply_custom"):
        stock = menu["stock"][name]
        expected = bytes.fromhex(stock["bytes"])
        require(at(_int(stock["va"]), len(expected)) == expected, "OG_MENU", f"{name} {stock['va']} is not the stock code")


def compose_ap(appfw: bytes, module: Module, layout: dict) -> bytes:
    """Place the module in appFw.so's zero gap, add its program headers and hooks; same length as the input."""
    from elftools.elf.elffile import ELFFile
    ap = layout["appfw"]
    require(digest(appfw) == layout["inputs"]["nflasha15:lib/appFw.so"] and len(appfw) == ap["input_bytes"],
            "OG_BASELINE", "appFw.so is not v0.1.3's")
    elf = ELFFile(io.BytesIO(appfw))
    phoff, phnum, phsize = elf["e_phoff"], elf["e_phnum"], elf["e_phentsize"]
    table = ap["program_headers"]
    require(phoff == _int(table["file_offset"]) and phnum == table["entries"] and phsize == _PHDR.size, "OG_BASELINE",
            "Unexpected program header table")
    gap, gap_end = _int(ap["free_gap"]["file_offset"]), _int(ap["free_gap"]["end"])
    require(gap_end - gap == ap["free_gap"]["bytes"] and not any(appfw[gap:gap_end]), "OG_BASELINE", "Gap not zero")
    new = [(5, _int(ap["rx"]["file_offset"]), module.text_va, len(module.text), _int(ap["rx"]["max_bytes"])),
           (6, _int(ap["rw"]["file_offset"]), module.state_va, _int(ap["rw"]["max_bytes"]), _int(ap["rw"]["max_bytes"]))]
    require(module.text_va == _int(ap["rx"]["va"]) and module.state_va == _int(ap["rw"]["va"])
            and module.state_bytes <= _int(ap["rw"]["max_bytes"]), "OG_LAYOUT", "Module VAs differ from layout.json")
    loads = [s for s in elf.iter_segments() if s["p_type"] == "PT_LOAD"]
    for flags, offset, va, size, room in new:
        require(size <= room and gap <= offset and offset + room <= gap_end and offset % 0x1000 == 0
                and (offset - va) % 0x10000 == 0, "OG_LAYOUT", "New section outside the gap or misaligned")
        for s in loads:
            start, end = s["p_vaddr"] & ~0xfff, (s["p_vaddr"] + s["p_memsz"] + 0xfff) & ~0xfff
            require(va + room <= start or va >= end, "OG_LAYOUT", f"New section at {va:#x} overlaps a segment")
            require(offset + room <= s["p_offset"] or offset >= s["p_offset"] + s["p_filesz"], "OG_LAYOUT",
                    "New section overlaps file-backed segment bytes")
    require(max(s["p_vaddr"] for s in loads) < module.text_va < module.state_va, "OG_LAYOUT", "PT_LOAD order")
    out = bytearray(appfw)
    rx_offset = new[0][1]
    out[rx_offset:rx_offset + len(module.text)] = module.text
    for index, (flags, offset, va, size, _) in enumerate(new, start=phnum):
        at = phoff + index * phsize
        require(not any(out[at:at + phsize]), "OG_BASELINE", "Program header slot not free")
        out[at:at + phsize] = _PHDR.pack(_PT_LOAD, flags, offset, va, va, size, size, 0x10000)
    struct.pack_into("<H", out, 0x38, phnum + len(new))
    first = _PHDR.unpack_from(out, phoff)
    require(first[0] == _PT_PHDR and first[5] == first[6] == phnum * phsize, "OG_BASELINE", "Unexpected _PT_PHDR")
    struct.pack_into("<QQ", out, phoff + 32, (phnum + len(new)) * phsize, (phnum + len(new)) * phsize)
    _check_menu_stock(appfw, elf, loads, layout)
    for hook in layout["hooks"]:
        va, link = _int(hook["va"]), {"bl": True, "b": False}[hook["kind"]]
        text = next(s for s in loads if s["p_vaddr"] <= va < s["p_vaddr"] + s["p_filesz"])
        at = text["p_offset"] + va - text["p_vaddr"]
        require(bytes(out[at:at + 4]) == _branch(va, _int(hook["previous_target"]), link), "OG_HOOK",
                f"{va:#x} does not hold the expected {hook['kind'].upper()}")
        out[at:at + 4] = _branch(va, module.symbols[hook["entry"]], link)
    result = bytes(out)
    require(len(result) == len(appfw), "OG_SIZE", "appFw.so changed size")
    check = ELFFile(io.BytesIO(result))
    segments = list(check.iter_segments())
    require(len(segments) == phnum + 2 and segments[-2]["p_vaddr"] == module.text_va, "OG_LAYOUT", "Re-read failed")
    return result


def _uxc_layout(data: bytes) -> tuple[int, int, int]:
    """(index slots, data base, first stored id) of an indexed UXC string bank (methods/07-custom-aspect-ratios)."""
    require(len(data) >= 16 and data[:4] == _UXC_MAGIC, "OG_UXC", "Not an indexed UXC string bank")
    count, rest = divmod(struct.unpack_from("<I", data, 12)[0], 0x1001)
    require(not rest and 0 < count <= 0x2000 and 16 + 2 * count <= len(data), "OG_UXC", "Bad UXC index bounds")
    return count, (16 + 2 * count + 3) & ~3, 0x1E000000 + (struct.unpack_from("<H", data, 10)[0] << 13)


def _uxc_record_bytes(text: bytes) -> int:
    return (4 + len(text) + 1 + 3) & ~3   # stored id, UTF-8, NUL, padding to 4


def _uxc_records(data: bytes) -> list[tuple[int, int, bytes]]:
    """Every live record as (file offset, text id, UTF-8 text), in file order; refuses overlaps and bad ids."""
    count, base, first = _uxc_layout(data)
    records = []
    for index in range(count):
        word = struct.unpack_from("<H", data, 16 + 2 * index)[0]
        if word == 0xFFFF:
            continue
        start = base + 4 * word
        end = data.find(b"\0", start + 4)
        require(start + 4 <= len(data) and struct.unpack_from("<I", data, start)[0] == first + index and end > 0,
                "OG_UXC", f"Bad record at index {index}")
        records.append((start, first + index - _UXC_ID_BIAS, data[start + 4:end]))
    records.sort()
    for (start, _, text), (after, _, _) in zip(records, records[1:]):
        require(start + _uxc_record_bytes(text) <= after, "OG_UXC", f"Overlapping records at {start:#x}")
    require(not records or records[-1][0] + _uxc_record_bytes(records[-1][2]) <= len(data), "OG_UXC", "Record past end")
    return records


def _uxc_texts(data: bytes) -> dict[int, str]:
    return {rid: text.decode("utf-8") for _, rid, text in _uxc_records(data)}


def _edit_bank(data: bytes, strings: dict) -> tuple[bytes, dict]:
    """Add the open-gate labels at empty index slots, shortening the listed custom-firmware texts to make room.

    Records keep their file order: those up to the last shortened one are packed again (the labels go right after the
    first shortened one), every record after it keeps its offset, and freed bytes left over are zeros, so the bank keeps
    its size and every 16-bit word offset only moves down. Nothing else changes."""
    count, base, first = _uxc_layout(data)
    records = _uxc_records(data)
    texts = {rid: text for _, rid, text in records}
    edits: dict[int, bytes] = {}
    for row in strings["shorten"]:
        rid = _int(row["id"])
        if texts.get(rid) == row["from"].encode("utf-8"):
            require(rid not in edits, "OG_UXC", f"{rid:#x} matches two shortenings")
            edits[rid] = row["to"].encode("utf-8")
    additions = [(_int(rid), text.encode("utf-8")) for rid, text in strings["add"].items()]
    for rid, _ in additions:
        index = rid + _UXC_ID_BIAS - first
        require(0 <= index < count and struct.unpack_from("<H", data, 16 + 2 * index)[0] == 0xFFFF, "OG_UXC",
                f"Index slot of {rid:#x} is not empty")
    require(edits, "OG_UXC", "No listed text to shorten in this bank")
    edited = [start for start, rid, _ in records if rid in edits]
    first_edit, last_edit = min(edited), max(edited)
    out, cursor = bytearray(data[:base]), base

    def place(rid: int, text: bytes) -> None:
        nonlocal cursor
        word = (cursor - base) // 4
        require(word < 0xFFFF, "OG_UXC", f"{rid:#x} would sit past the 16-bit word offsets")
        struct.pack_into("<H", out, 16 + 2 * (rid + _UXC_ID_BIAS - first), word)
        record = struct.pack("<I", rid + _UXC_ID_BIAS) + text + b"\0"
        out.extend(record + bytes(_uxc_record_bytes(text) - len(record)))
        cursor += _uxc_record_bytes(text)

    for start, rid, text in records:
        if start > last_edit:
            require(cursor <= start, "OG_UXC", "The shortened texts do not free enough bytes")
            out.extend(bytes(start - cursor) + data[start:])
            break
        place(rid, edits.get(rid, text))
        if start == first_edit:
            for addition in additions:
                place(*addition)
    else:
        require(cursor <= len(data), "OG_UXC", "The shortened texts do not free enough bytes")
        out.extend(bytes(len(data) - cursor))
    result = bytes(out)
    expected = {rid: text.decode("utf-8") for rid, text in (texts | edits | dict(additions)).items()}
    require(len(result) == len(data) and _uxc_texts(result) == expected, "OG_UXC", "Edited bank does not read back")
    freed = sum(_uxc_record_bytes(texts[rid]) - _uxc_record_bytes(text) for rid, text in edits.items())
    return result, {"shortened": {f"{rid:#010x}": [texts[rid].decode("utf-8"), text.decode("utf-8")]
                                  for rid, text in sorted(edits.items())},
                    "freed_bytes": freed, "label_bytes": sum(_uxc_record_bytes(t) for _, t in additions)}


def _edit_banks(read, strings: dict) -> dict[str, tuple[bytes, bytes, dict]]:
    """{path: (old, new, evidence)} for the 68 horizontal/vertical banks; read(path) returns a bank's bytes."""
    from .custom_sound import REQUIRED_RESOURCE_PATHS
    paths = sorted(REQUIRED_RESOURCE_PATHS)
    require(len(paths) == strings["banks"], "OG_UXC", "Unexpected string bank list")
    result = {}
    for path in paths:
        old = read(path)
        new, evidence = _edit_bank(old, strings)
        require(set(evidence["shortened"]) >= {"0x0200ab61", "0x0200ab62", "0x0200ab63"}, "OG_UXC",
                f"{path}: the sound confirmation texts are not the expected v0.1.3 ones")
        result[path] = (old, new, evidence)
    return result


def apply_file_edits(fat: Fat, edits: Sequence[FileEdit]) -> None:
    for path in dict.fromkeys(e.path for e in edits):
        data = bytearray(fat.read(path))
        for e in (e for e in edits if e.path == path):
            require(data[e.offset:e.offset + len(e.old)] == e.old and len(e.old) == len(e.new), "OG_STOCK",
                    f"{path} {e.offset:#x}: not the expected stock bytes")
            data[e.offset:e.offset + len(e.new)] = e.new
        fat.replace(path, bytes(data))
        require(fat.read(path) == bytes(data), "OG_FAT", f"{path} did not read back")


def _changed_regions(a: bytes, b: bytes, gap: int = 256) -> list[dict]:
    """Where two same-length files differ: regions [offset, offset + bytes) holding `changed` differing bytes."""
    import numpy as np
    changed = np.flatnonzero(np.frombuffer(a, dtype=np.uint8) != np.frombuffer(b, dtype=np.uint8)).tolist()
    regions: list[list[int]] = []
    for i in changed:
        if regions and i - regions[-1][1] <= gap:
            regions[-1][1], regions[-1][2] = i + 1, regions[-1][2] + 1
        else:
            regions.append([i, i + 1, 1])
    return [{"offset": hex(s), "bytes": e - s, "changed": n} for s, e, n in regions]


def _audit(dat: Path, plain: Path, public_pem: bytes, marker: bytes) -> dict:
    """tools/verify_sd_package.py's independent audit, as {"passed": True, ...} or {"passed": False, "error": ...}."""
    spec = importlib.util.spec_from_file_location("verify_sd_package", _ROOT / "tools/verify_sd_package.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    try:
        return {"passed": True} | module.verify(dat, plain, public_pem, marker)
    except ValueError as error:
        return {"passed": False, "error": str(error)}


def build(args: argparse.Namespace) -> dict:
    """decode -> check_stock -> DmmCfg.bin -> compile_module -> compose_ap -> 68 string banks -> ext_replace -> sums ->
    encode -> resign."""
    from cryptography.hazmat.primitives import serialization
    from dissect.extfs import ExtFS
    from .firmware import decode, encode, exact, ext_replace, tar_index, update_sum
    from .offline import resign
    lay = _layout()
    output = Path(args.output)
    require(not output.exists(), "EXISTS", "Choose a new output directory")
    require(sha256(args.base) == lay["base_package"]["sha256"], "BASELINE", "Only custom firmware v0.1.3's DAT is supported")
    require(sha256(args.zig) == lay["compiler"]["sha256"], "OG_COMPILER", "Zig binary is not the pinned one")
    private = serialization.load_pem_private_key(Path(args.private_key).read_bytes(), None)
    public_pem = Path(args.public_key).read_bytes()
    require(private.public_key().public_numbers() == serialization.load_pem_public_key(public_pem).public_numbers(),
            "KEY", "Package key differs from updater key")
    image = compile_image(Path(args.designs), _STORED_RECORD)
    output.mkdir(parents=True)
    work = output / "work"
    work.mkdir()
    plain = work / "plain.bin"
    initial = decode(args.base, output=plain)
    require(initial["plaintext_sha256"] == lay["base_package"]["plaintext_sha256"], "BASELINE", "Plaintext identity")
    index = tar_index(plain)
    changes: dict[str, tuple[bytes, bytes]] = {}
    with plain.open("r+b") as stream:
        def read(name):
            offset, size = index[name]
            stream.seek(offset)
            return exact(stream, size)

        def write(name, before, after):
            offset, size = index[name]
            require(len(before) == len(after) == size, "SIZE", "TAR member must retain its size")
            stream.seek(offset)
            stream.write(after)
            changes[name] = (before, after)

        p15, p8 = read(_AP15), read(_CP8)
        ext, fat8 = ExtFS(io.BytesIO(p15)), Fat(p8)
        appfw, libmpr = ext.get("lib/appFw.so").open().read(), ext.get("lib/libmpr.so").open().read()
        cpapp, dmmcfg = fat8.read("CPAPP-B.BIN"), fat8.read("DMMCFG.BIN")
        avcam = Fat(read(_AV3)).read("AV-CAM.BIN")
        files = {"nflasha15:lib/appFw.so": appfw, "nflasha15:lib/libmpr.so": libmpr, "nflasha8:CPAPP-B.BIN": cpapp,
                 "nflasha8:DMMCFG.BIN": dmmcfg, "nflasha3:av-cam.bin": avcam}
        for key, data in files.items():
            require(digest(data) == lay["inputs"][key], "BASELINE", f"{key} is not v0.1.3's")
        check_stock(image, {"cpapp-b.bin": cpapp, "av-cam.bin": avcam, "libmpr.so": libmpr})
        cam = lay["camera"]
        lo, hi = _int(cam["avcam_map_offset"]), _int(cam["avcam_map_offset"]) + _int(cam["avcam_map_bytes"])
        require(all(lo <= r.addr and r.addr + len(r.old) <= hi for p in image.presets for r in p.runs
                    if r.space is Space.AVCAM), "OG_LAYOUT", "An av-cam.bin site is outside the mapped window")
        edits = dmmcfg_edits(Path(args.designs))
        apply_file_edits(fat8, edits)
        write(_CP8, p8, fat8.bytes())
        module = compile_module(Path(args.zig), image, work / "module")
        ap = compose_ap(appfw, module, lay)
        banks = _edit_banks(lambda path: ext.get(path).open().read(), lay["menu"]["strings"])
        p15_new = ext_replace(p15, "lib/appFw.so", ap, lay["inputs"]["nflasha15:lib/appFw.so"])
        for path, (old, new, _) in banks.items():
            p15_new = ext_replace(p15_new, path, new, digest(old))
        write(_AP15, p15, p15_new)
        old_sum = read(_PART_SUM)
        write(_PART_SUM, old_sum, update_sum(old_sum, {k.removeprefix("0700_part_image/"): v
                                                      for k, v in changes.items()}))
        marker = read(_WARM_BOOT)[:4]
    require(tar_index(plain) == index, "TAR", "TAR layout changed")
    baseline = work / "original.bin"
    decode(args.base, output=baseline)
    with baseline.open("rb") as old, plain.open("rb") as new:
        for name, (offset, size) in index.items():
            old.seek(offset)
            new.seek(offset)
            different = False
            for start in range(0, size, 4 << 20):
                amount = min(4 << 20, size - start)
                different |= exact(old, amount) != exact(new, amount)
            require(different == (name in changes), "DIFF", "Unexpected changed/unchanged TAR member: " + name)
    unsigned = work / "UNSIGNED_DO_NOT_INSTALL.DAT"
    encoding = encode(args.base, plain, unsigned)
    final = output / "BODYDATA.DAT"
    signing = resign(unsigned, args.private_key, final)
    final_decoding = decode(final, compare=plain)
    audit = _audit(final, plain, public_pem, marker)
    require(audit["passed"], "AUDIT", f"verify_sd_package fails on the output: {audit.get('error')}")
    after = Fat(changes[_CP8][1]).read("DMMCFG.BIN")
    report = {
        "base_sha256": lay["base_package"]["sha256"], "base_plaintext_sha256": initial["plaintext_sha256"],
        "output_sha256": sha256(final), "inputs": {k: digest(v) for k, v in files.items()},
        "designs": lay["designs"], "compiler": lay["compiler"], "sources": _check_sources(lay),
        "site_image": {"sha256": digest(image.encode()), "bytes": len(image.encode()),
                       "presets": [{"mode": p.mode.name, "family": p.family.value, "runs": len(p.runs),
                                    "bytes": sum(len(r.old) for r in p.runs)} for p in image.presets]},
        "module": {"text_va": hex(module.text_va), "text_bytes": len(module.text), "text_sha256": digest(module.text),
                   "state_va": hex(module.state_va), "state_bytes": module.state_bytes,
                   "symbols": {k: hex(v) for k, v in sorted(module.symbols.items()) if not k.startswith("$")}},
        "appfw": {"input_sha256": digest(appfw), "output_sha256": digest(ap),
                  "changed_regions": _changed_regions(appfw, ap)},
        "dmmcfg": {"input_sha256": digest(dmmcfg), "output_sha256": digest(after),
                   "changed_regions": _changed_regions(dmmcfg, after, gap=0)},
        "string_banks": {path: {"input_sha256": digest(old), "output_sha256": digest(new), "bytes": len(new),
                                "changed_regions": _changed_regions(old, new, gap=16)} | evidence
                         for path, (old, new, evidence) in banks.items()},
        "changed_members": sorted(changes), "warm_boot_marker": marker.decode("ascii"),
        "encoding": encoding, "signing": signing, "final_decoding": final_decoding, "verify_sd_package": audit,
        "camera_io": False, "camera_tested": False,
    }
    (output / "verification.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    return report


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    package = sub.add_parser("build", help="Build and sign an open-gate BODYDATA.DAT from v0.1.3's")
    for name in ("base", "designs", "zig", "private-key", "public-key", "output"):
        package.add_argument("--" + name, type=Path, required=True)
    args = parser.parse_args()
    report = build(args)
    print(json.dumps({k: report[k] for k in ("output_sha256", "changed_members", "appfw", "dmmcfg", "module")},
                     indent=2))


if __name__ == "__main__":
    main()
